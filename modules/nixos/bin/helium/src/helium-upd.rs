// writes the latest helium release into release.nix.

use std::{
    env, fs,
    process::{Command, Stdio},
};

const API: &str = "https://api.github.com/repos/imputnet/helium-linux/releases/latest";
const ASSET: &str = "x86_64_linux.tar.xz";
const OUTPUT: &str = "modules/nixos/bin/helium/release.nix";

fn main() {
    if let Err(e) = update() {
        eprintln!("\x1b[1;31m✗\x1b[0m \x1b[1mhelium\x1b[0m: {e}");
        std::process::exit(1);
    }
}

fn update() -> Result<(), String> {
    let root = env::args().nth(1).unwrap_or_else(|| ".".into());
    let file = format!("{root}/{OUTPUT}");

    let json_path = env::temp_dir().join(format!("helium-release-{}.json", std::process::id()));
    let json = json_path.to_str().ok_or("temp path is not utf-8")?;

    run("curl", &["-fsSL", "-o", json, API])?;

    let version = run("jq", &["-r", ".tag_name", json])?;
    let filter = format!(".assets[] | select(.name | endswith(\"{ASSET}\")) | .digest");

    let digest = run("jq", &["-r", &filter, json])?;
    let _ = fs::remove_file(json);

    let digest = digest
        .strip_prefix("sha256:")
        .filter(|d| d.len() == 64 && d.chars().all(|c| c.is_ascii_hexdigit()))
        .ok_or_else(|| format!("unexpected digest: {digest}"))?;
    if version.is_empty() || !version.chars().all(|c| c.is_ascii_digit() || c == '.') {
        return Err(format!("unexpected version: {version}"));
    }

    let asset = format!("helium-{version}-{ASSET}");

    let contents = format!(
r#"# autogenerated
{{
  version = "{version}";
  assets = {{
    x86_64-linux = {{
      url = "https://github.com/imputnet/helium-linux/releases/download/{version}/{asset}";
      sha256 = "{digest}";
    }};
  }};
}}
"#
    );

    let existing = fs::read_to_string(&file).ok();
    if existing.as_deref() == Some(contents.as_str()) {
        // TODO: print somethign here maybe
        return Ok(());
    }

    let tmp = format!("{file}.tmp");
    fs::write(&tmp, &contents).map_err(|e| format!("write {tmp}: {e}"))?;
    fs::rename(&tmp, &file).map_err(|e| format!("rename {tmp}: {e}"))?;

    println!("\x1b[1;32m↑\x1b[0m \x1b[1;35mhelium\x1b[0m \x1b[1;32m{version}\x1b[0m");
    Ok(())
}

fn run(cmd: &str, args: &[&str]) -> Result<String, String> {
    let out = Command::new(cmd)
        .args(args)
        .stderr(Stdio::inherit())
        .output()
        .map_err(|e| format!("{cmd}: {e}"))?;
    if !out.status.success() {
        return Err(format!("{cmd} failed ({})", out.status));
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}
